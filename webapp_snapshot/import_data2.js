async function main() {
  const rows = data.split('\n');
  const items = [];
  
  rows.forEach((row) => {
    const cols = row.split('\t');
    const concepto = cols[0].trim();
    
    for (let m = 1; m <= 12; m++) {
      const idx_c = 4 + (m - 1) * 4 + 0;
      const idx_r = 4 + (m - 1) * 4 + 1;
      const idx_dif = 4 + (m - 1) * 4 + 2;
      const idx_total = 4 + (m - 1) * 4 + 3;
      
      const parse = (c) => {
          if (!cols[c]) return 0;
          const val = parseFloat(cols[c].replace(/\./g, '').replace(',', '.'));
          return isNaN(val) ? 0 : val;
      };

      const c = parse(idx_c);
      const r = parse(idx_r);
      const dif = parse(idx_dif);
      const total = parse(idx_total);

      if (c > 0 || r > 0 || dif > 0 || total > 0) {
        items.push({
          year: 2026,
          month: m,
          grupo: 'Gastos Variables',
          concepto: concepto,
          importe_c: c,
          importe_r: r,
          importe_dif: dif,
          importe_total: total
        });
      }
    }
  });

  await prisma.$transaction(
    items.map(item => 
      prisma.gastoMensual.upsert({
        where: { year_month_grupo_concepto: { year: item.year, month: item.month, grupo: item.grupo, concepto: item.concepto } },
        update: { importe_c: item.importe_c, importe_r: item.importe_r, importe_dif: item.importe_dif, importe_total: item.importe_total },
        create: item
      })
    )
  );
}

main().catch(console.error).finally(() => prisma.$disconnect());
